    if nm in ("공작기계조작원(CNC)", "용접원", "산업용로봇조작원", "목공", "배관원", "전공(전기 설비)", "자동차정비원", "항공기정비원"): return "기술"
    if nm in ("제과사 및 제빵사", "조리사 및 주방장", "곤충 음식 개발자·조리사"): return "요리"
    if nm in ("비행기조종사", "철도 및 지하철기관사", "도심항공교통(UAM) 조종사"): return "하늘"
    if nm == "기술·가정 교사": return "교육"
    if nm == "보육교사": return "보육"
    if nm in ("스마트팜 운영자", "정밀 농업기술자"): return "농업"
    if "디자이너" in nm or "디자인" in nm or nm == "푸드스타일리스트": return "디자인"
    if "연구" in nm or nm == "종자 개발자(육종 연구원)" or nm == "인공위성개발원": return "연구"
    if any(k in nm for k in ("변리사", "심사관", "영양사", "설계사", "상수도", "컨설턴트", "어드바이저", "복지사", "플래너", "협력", "공정무역", "기후변화", "재활용", "산업안전", "전문가")) and "엔지니어" not in nm:
        return "전문가"
