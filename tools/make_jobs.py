FIELD_TAGS = {"발명·디자인": ["발명"], "제조": ["제조"], "건설": ["건설"], "수송": ["수송"], "정보통신": ["정보통신"],
              "생명": ["생명"], "적정기술·환경·에너지": ["적정기술"], "가정": ["가정"], "교육": []}
